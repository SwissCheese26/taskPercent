const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  report: (s) => ipcRenderer.send('battery:report', s),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.send('settings:set', s),
  onSettings: (cb) => ipcRenderer.on('settings:changed', (_e, s) => cb(s)),
  testWarning: () => ipcRenderer.send('toast:test'),
  closeToast: () => ipcRenderer.send('toast:close'),
  openDevices: () => ipcRenderer.send('devices:open'),
  closeDevices: () => ipcRenderer.send('devices:close'),
  audioList: () => ipcRenderer.invoke('audio:list'),
  audioVolume: (id, value) => ipcRenderer.invoke('audio:volume', { id, value }),
  audioMute: (id, value) => ipcRenderer.invoke('audio:mute', { id, value }),
  btList: () => ipcRenderer.invoke('bt:list'),
  btAction: (id, action) => ipcRenderer.invoke('bt:action', { id, action }),
  adminStatus: () => ipcRenderer.invoke('admin:status'),
  adminSetup: () => ipcRenderer.invoke('admin:setup'),
  adminRemove: () => ipcRenderer.invoke('admin:remove'),
  periphPin: (id, on) => ipcRenderer.invoke('periph:pin', { id, on }),
  periphPinned: () => ipcRenderer.invoke('periph:pinned'),
  periphReport: (items) => ipcRenderer.send('periph:report', items),
  onPeriphRefresh: (cb) => ipcRenderer.on('periph:refresh', cb),
  onDevicesTab: (cb) => ipcRenderer.on('devices:tab', (_e, t) => cb(t)),
  periphList: () => ipcRenderer.invoke('periph:list'),
  quit: () => ipcRenderer.send('app:quit'),
});
